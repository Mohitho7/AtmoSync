CREATE DATABASE IF NOT EXISTS ATMOSYNC;

CREATE SCHEMA IF NOT EXISTS ATMOSYNC.RAW;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.STAGING;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.ANALYTICS;

CREATE TABLE IF NOT EXISTS ATMOSYNC.RAW.SENSOR_EVENTS (
    EVENT_ID VARCHAR(36) NOT NULL,
    SHIPMENT_ID VARCHAR(256) NOT NULL,
    CONTAINER_ID VARCHAR(256) NOT NULL,
    SENSOR_ID VARCHAR(256) NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP_TZ NOT NULL,
    KAFKA_TOPIC VARCHAR(256) NOT NULL,
    KAFKA_PARTITION NUMBER(10, 0) NOT NULL,
    KAFKA_OFFSET NUMBER(38, 0) NOT NULL,
    INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    PAYLOAD VARIANT NOT NULL,
    PAYLOAD_SHA256 VARCHAR(64) NOT NULL,
    CONSTRAINT PK_SENSOR_EVENTS PRIMARY KEY (
        KAFKA_TOPIC, KAFKA_PARTITION, KAFKA_OFFSET
    )
);
